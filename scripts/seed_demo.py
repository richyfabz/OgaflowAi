def sql_value(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def render_seed() -> str:
    """Generate inserts that fail on an occupied fixture namespace, without overwrites."""
    lines = [
        "-- Generated by scripts/seed_demo.py. Synthetic data; no real payment verification.",
        "BEGIN;",
    ]
    for table, rows in demo_records().items():
        for row in rows:
            columns = ", ".join(row)
            values = ", ".join(sql_value(value) for value in row.values())
            lines.append(f"INSERT INTO {table} ({columns}) VALUES ({values});")
    return "\n".join([*lines, "COMMIT;", ""])


